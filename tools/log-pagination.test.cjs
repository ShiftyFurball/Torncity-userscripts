const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('torn-tax-tracker.user.js','utf8');
const start = source.indexOf('  async function fetchAllLogs(');
const end = source.indexOf('  function determineLogStartUnix', start);
const calls = [];
let responses = [];
const ctx = vm.createContext({Date, DEFAULT_SETTINGS:{maxLogPages:25}, tornFetch:async (url,params) => { calls.push(params); return responses.shift(); }});
vm.runInContext(source.slice(start,end), ctx);
function page(oldest) { return Object.fromEntries(Array.from({length:100},(_,i) => ['log-'+(oldest+i),{timestamp:oldest+i}])); }
(async () => {
  responses = [{log:page(200)},{log:{'log-200':{timestamp:200},c:{timestamp:200},d:{timestamp:100}}}];
  let result = await ctx.fetchAllLogs('',100,5);
  assert.equal(Object.keys(result.logs).length,102);
  assert.equal(calls[1].to,200);
  assert.equal(result.hitPageLimit,false);
  assert.equal(calls[0].limit,100);
  responses = [{log:page(300)}];
  result = await ctx.fetchAllLogs('',100,1);
  assert.equal(result.hitPageLimit,true);
  responses = [{log:page(300)},{log:page(300)}];
  result = await ctx.fetchAllLogs('',100,5);
  assert.equal(result.hitPageLimit,true);
  responses = [{log:{a:{timestamp:300}}}];
  result = await ctx.fetchAllLogs('4800',100,1);
  assert.equal(result.hitPageLimit,false, 'a short final page must be complete');
  assert.equal(calls.at(-1).log,'4800');
  assert.equal(responses.length,0);
  const ids = ctx.receiptLogTypesFromCatalog({'1':'Money receive','2':'Item receive','3':'Money send','4':'Attack win','5':'Company funds deposit','6':'Item market buy'});
  assert.deepEqual(Array.from(ids),['1','2','5']);
  const normalized = ctx.receiptLogTypesFromCatalog([{id:10,title:'Money receive'},{id:11,title:'Item receive'}]);
  assert.deepEqual(Array.from(normalized),['10','11']);
  ctx.setStatus = () => {};
  responses = [{log:{cash:{timestamp:300}}},{log:{item:{timestamp:200}}}];
  result = await ctx.fetchReceiptLogs(['1','2'],100,1);
  assert.equal(Object.keys(result.logs).length,2);
  assert.equal(result.hitPageLimit,false);
  assert.deepEqual(calls.slice(-2).map(c=>c.log),['1','2']);
  responses = [{}];
  await assert.rejects(ctx.fetchAllLogs('',100,5), /no log collection/);
  console.log('Timestamp overlap, deduplication, partial history and malformed responses passed.');
})().catch(error => { console.error(error); process.exitCode=1; });
